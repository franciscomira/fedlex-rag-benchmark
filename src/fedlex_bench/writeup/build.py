"""Assemble the post: tokenize and fill the template, then write Markdown, HTML and figures."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from html import escape
from pathlib import Path

from fedlex_bench.serve.notices import NOT_LEGAL_ADVICE, NOT_OFFICIAL_DE, NOT_OFFICIAL_EN
from fedlex_bench.site.build import Report
from fedlex_bench.site.render import page_shell
from fedlex_bench.writeup.figures import Figure
from fedlex_bench.writeup.markdown import fill_markdown, parse_blocks, plain, render_html
from fedlex_bench.writeup.numbers import Offence, check_numbers, load_allowlist
from fedlex_bench.writeup.placeholders import BuildError, PlaceholderError, Resolver, tokenize

WRITEUP_DIR = Path("docs") / "writeup"
TEMPLATE = WRITEUP_DIR / "post.template.md"
FACTS = WRITEUP_DIR / "facts.json"
ALLOWLIST = WRITEUP_DIR / "numbers_allowlist.txt"
POST_MD = WRITEUP_DIR / "post.md"
FIGURES_DIR = WRITEUP_DIR / "figures"
POST_HTML = "post.html"
GENERATED_NOTE = (
    "<!-- GENERATED by `uv run python -m fedlex_bench.writeup build` from "
    "docs/writeup/post.template.md; do not edit. -->"
)
FOOT = (
    "Statute text is not shown on this page. Built by "
    "<code>uv run python -m fedlex_bench.writeup build</code> from "
    "<code>docs/writeup/post.template.md</code> and the committed files under "
    "<code>eval/</code>; no script, font or tracker is loaded from elsewhere."
)


@dataclass
class Post:
    title: str
    markdown: str
    html: str
    figures: dict[str, Figure]
    offences: list[Offence] = field(default_factory=list)


def notices_markdown() -> str:
    return f"> {NOT_OFFICIAL_EN} {NOT_OFFICIAL_DE} {NOT_LEGAL_ADVICE}"


def with_notices(markdown: str) -> str:
    """Notices right after the title (or at the top) and again at the end."""
    lines = markdown.rstrip("\n").split("\n")
    at = next((i + 1 for i, line in enumerate(lines) if line.strip()), 0)
    top = at if lines[at - 1].startswith("# ") else 0
    lines[top:top] = ["", notices_markdown()] if top else [notices_markdown(), ""]
    return "\n".join([GENERATED_NOTE, *lines, "", "---", "", notices_markdown()]) + "\n"


def description_of(markdown_lines: list[str], title: str) -> str:
    for line in markdown_lines:
        text = line.strip()
        if text and not text.startswith(("#", ">", "|", "-", "*", "`", "!", "<")):
            text = re.sub(r"\s+", " ", plain(text, []))
            return text if len(text) <= 200 else text[:197].rsplit(" ", 1)[0] + "..."
    return title


def build_post(report: Report, template: str, root: Path, *, source: str = TEMPLATE.as_posix(),
               allowlist: Path | None = None, has_examples: bool = True) -> Post:
    resolver = Resolver(report, root / FACTS)
    tok = tokenize(template, resolver, source)
    blocks = parse_blocks(tok)
    title, main, nav_entries = render_html(blocks, tok.items)
    if not title:
        raise BuildError([f"{source}: the template must start with a '# Title' heading"])
    nav = "".join(f'<a href="#{escape(i, quote=True)}">{escape(t)}</a>' for i, t in nav_entries)
    nav += '<a href="index.html">Results</a>'
    if has_examples:
        nav += '<a href="examples.html">Recorded examples</a>'
    description = description_of(fill_markdown(tok).split("\n"), title)
    html = page_shell(title, description, nav, main, FOOT)
    offences = check_numbers(tok.lines, load_allowlist(allowlist))
    try:
        figures = resolver.figures()
    except PlaceholderError as exc:
        raise BuildError([f"{source}: {exc}"]) from exc
    return Post(title, with_notices(fill_markdown(tok)), html, figures, offences)
