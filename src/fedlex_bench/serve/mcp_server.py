"""Stdio MCP server over the serving pipeline (search, exact lookup, cited answers).

    uv run --group serve python -m fedlex_bench.serve.mcp_server

Tools:
  list_acts()                          which acts (SR numbers) the corpus slice covers
  search_articles(query, k)            tuned int8 embedder only: no LLM, no key, no cost
  get_article(article_id)              exact lookup, full DE/FR/IT text
  answer_with_citations(question, language)   the measured pipeline; needs ANTHROPIC_API_KEY

Rules kept here:
  * stdout belongs to the MCP protocol; logs go to stderr and never contain questions or keys.
  * The model is loaded on first use, so the server starts instantly.
  * Article ids, titles and statute text come from the corpus; citations are validated by code
    (`n_invalid_ids` counts what the model invented and code dropped).
  * Every result carries the notices from `serve.notices`.
"""

from __future__ import annotations

import logging
import os
import re
import sys
import threading
from collections.abc import Callable
from typing import TYPE_CHECKING, Annotated, Any, Literal, Protocol

from mcp.server.mcpserver import MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from pydantic import Field

from fedlex_bench.serve import notices

if TYPE_CHECKING:  # the pipeline pulls in pandas/onnx: import it lazily, not at server start
    from fedlex_bench.serve.pipeline import ArticleHit, AskResult

log = logging.getLogger("fedlex_bench.serve.mcp")

SERVER_NAME = "fedlex-rag"
MAX_QUESTION_CHARS = 1000  # equals serve.pipeline.MAX_QUESTION_CHARS (checked in the tests)
MAX_QUERY_CHARS = MAX_QUESTION_CHARS
MAX_K = 50
SNIPPET_CHARS = 140
ARTICLE_ID_RE = re.compile(r"^\d+(?:\.\d+)*:[0-9A-Za-z._/-]{1,24}$")
LANGS = ("de", "fr", "it")

SOURCE_NOTE = (
    "Statute text (titles, article texts, source URLs) is verbatim Fedlex data, unaltered. "
    "Rankings, scores, answers and the choice of citations are generated by this project "
    "(a fine-tuned embedder and an LLM) and are not part of the statute."
)

INSTRUCTIONS = (
    "Retrieval over a slice of Swiss federal law (German, French and Italian text), with "
    "article-level citations. Use list_acts to see which acts are covered; anything else is "
    "not in the sources. "
    f"{notices.NOT_OFFICIAL_EN} {notices.NOT_LEGAL_ADVICE}"
)


class PipelineLike(Protocol):
    """What the server needs from `serve.pipeline.ServingPipeline` (tests inject a fake)."""

    def search(self, query: str, k: int = 10) -> list[ArticleHit]: ...
    def get_article(self, article_id: str) -> ArticleHit | None: ...
    def ask(self, query: str, query_lang: str = "en", n_hits: int = 10) -> AskResult: ...


def _default_key_available() -> bool:
    """ANTHROPIC_API_KEY from the environment or the repo's .env (where the harness reads it)."""
    try:
        from dotenv import load_dotenv

        from fedlex_bench.llm.config import repo_root

        load_dotenv(repo_root() / ".env")
    except Exception:  # a missing .env or package must not hide the answer: fall back to the env
        log.warning("could not read .env")
    return bool(os.environ.get("ANTHROPIC_API_KEY", "").strip())


def _notices() -> dict[str, str]:
    return {
        "not_official_en": notices.NOT_OFFICIAL_EN,
        "not_official_de": notices.NOT_OFFICIAL_DE,
        "not_legal_advice": notices.NOT_LEGAL_ADVICE,
        "source_note": SOURCE_NOTE,
    }


def _wrap(**payload: Any) -> dict[str, Any]:
    """Every tool result: the notices first, then the payload."""
    return {"notices": _notices(), **payload}


def _snippet(text: str, limit: int = SNIPPET_CHARS) -> str:
    flat = " ".join(text.split())
    if len(flat) <= limit:
        return flat
    cut = flat[:limit].rsplit(" ", 1)[0] or flat[:limit]
    return cut + " ..."


def _summary(hit: ArticleHit) -> dict[str, Any]:
    """An article without its full text: title and a short snippet per language."""
    return {
        "article_id": hit.article_id,
        "sr": hit.sr,
        "titles": hit.titles,
        "snippets": {lang: _snippet(t) for lang, t in hit.texts.items()},
        "source_urls": hit.source_urls,
        "is_repealed": hit.is_repealed,
        "consolidation_date": hit.consolidation_date,
    }


def _pointer(hit: ArticleHit) -> dict[str, Any]:
    """A citation or pointer: id and titles; the caller fetches the text with get_article."""
    return {
        "article_id": hit.article_id,
        "sr": hit.sr,
        "titles": hit.titles,
        "is_repealed": hit.is_repealed,
        "source_urls": hit.source_urls,
    }


def _clean_text(value: str, what: str, limit: int) -> str:
    value = (value or "").strip()
    if not value:
        raise ToolError(f"{what} is empty.")
    if len(value) > limit:
        raise ToolError(f"{what} is longer than {limit} characters ({len(value)}).")
    return value


def _corpus_acts(pipeline: Any) -> list[dict[str, Any]]:
    """Per act: SR number, name, article count and consolidation date, read from the corpus."""
    try:
        from fedlex_bench.benchmark.common import ACT_NAMES
    except Exception:  # names are a convenience; the SR numbers come from the corpus
        ACT_NAMES = {}
    articles = pipeline.env.articles
    rows = []
    for sr, grp in sorted(articles.groupby("sr"), key=lambda kv: str(kv[0])):
        rep = grp[grp["is_repealed"].astype(bool)]
        dates = sorted({str(d) for d in grp.get("consolidation_date", []) if d})
        rows.append(
            {
                "sr": str(sr),
                "name": ACT_NAMES.get(str(sr), ""),
                "n_articles": int(grp["article_id"].nunique()),
                "n_repealed": int(rep["article_id"].nunique()),
                "consolidation_date": dates[-1] if dates else "",
            }
        )
    return rows


def create_server(
    pipeline: PipelineLike | None = None,
    *,
    api_key_available: Callable[[], bool] = _default_key_available,
) -> MCPServer:
    """Build the MCP server. `pipeline=None` makes the real one lazily on the first tool call."""
    lock = threading.Lock()
    state: dict[str, Any] = {"pipeline": pipeline}

    def get_pipeline() -> Any:
        with lock:
            if state["pipeline"] is None:
                log.info("loading the serving pipeline (first use)")
                from fedlex_bench.serve.pipeline import ServingPipeline

                state["pipeline"] = ServingPipeline()
            return state["pipeline"]

    server = MCPServer(SERVER_NAME, instructions=INSTRUCTIONS)

    @server.tool()
    def list_acts() -> dict[str, Any]:
        """List the acts (SR numbers) this server covers. Only these are searchable; it is a
        slice of Swiss federal law, not all of Fedlex. Names are English working titles."""
        acts = _corpus_acts(get_pipeline())
        return _wrap(
            n_acts=len(acts),
            acts=acts,
            languages=list(LANGS),
            coverage_note=(
                "Only these acts are in the corpus. Questions about other statutes, ordinances or "
                "case law are not in the sources."
            ),
        )

    @server.tool()
    def search_articles(
        query: Annotated[
            str, Field(description="Question or keywords, in German, French, Italian or English.")
        ],
        k: Annotated[
            int, Field(ge=1, le=MAX_K, description=f"Number of articles (1 to {MAX_K}).")
        ] = 10,
    ) -> dict[str, Any]:
        """Rank corpus articles for a query with the fine-tuned multilingual embedder only. No LLM,
        no API key, no cost. Returns ids, titles (DE/FR/IT), score and a short snippet, not the full
        text: call get_article for that. The score is a similarity, not a probability."""
        query = _clean_text(query, "query", MAX_QUERY_CHARS)
        if not 1 <= k <= MAX_K:
            raise ToolError(f"k must be between 1 and {MAX_K}, got {k}.")
        try:
            hits = get_pipeline().search(query, k=k)
        except ToolError:
            raise
        except ValueError as e:
            raise ToolError(str(e)) from e
        except Exception as e:
            log.error("search failed: %s", type(e).__name__)
            raise ToolError(
                f"Search failed ({type(e).__name__}); see the server log on stderr."
            ) from e
        return _wrap(
            n_results=len(hits),
            results=[{"rank": h.rank, "score": h.score, **_summary(h)} for h in hits],
            cost_usd=0.0,
        )

    @server.tool()
    def get_article(
        article_id: Annotated[
            str, Field(description='Article id "<SR>:<article>", e.g. "220:257d".')
        ],
    ) -> dict[str, Any]:
        """Exact lookup of one article by id: full German, French and Italian text (verbatim
        Fedlex), repealed flag, consolidation date and source URLs. Unknown ids are an error."""
        article_id = (article_id or "").strip()
        if not ARTICLE_ID_RE.match(article_id):
            raise ToolError(
                f"Invalid article id {article_id[:40]!r}. "
                'Expected "<SR>:<article>", e.g. "220:257d".'
            )
        try:
            hit = get_pipeline().get_article(article_id)
        except Exception as e:
            log.error("get_article failed: %s", type(e).__name__)
            raise ToolError(
                f"Lookup failed ({type(e).__name__}); see the server log on stderr."
            ) from e
        if hit is None:
            raise ToolError(
                f"Unknown article id {article_id!r}: not in the corpus. "
                "Use search_articles to find "
                "ids and list_acts to see which acts are covered."
            )
        return _wrap(
            article_id=hit.article_id,
            sr=hit.sr,
            titles=hit.titles,
            texts=hit.texts,
            source_urls=hit.source_urls,
            is_repealed=hit.is_repealed,
            consolidation_date=hit.consolidation_date,
        )

    @server.tool()
    def answer_with_citations(
        question: Annotated[
            str, Field(description=f"The question (at most {MAX_QUESTION_CHARS} characters).")
        ],
        language: Annotated[
            Literal["en", "de", "fr", "it"],
            Field(description="Language of the question and of the answer."),
        ] = "en",
    ) -> dict[str, Any]:
        """The full measured pipeline: tuned retrieval, LLM rerank, cited answer. Costs a few cents
        per call and needs ANTHROPIC_API_KEY (the monthly budget cap in config.toml applies).
        status is "answered" or "refused" (the sources do not contain the answer). Citation and
        pointer ids are checked by code against the retrieved articles; invented ids are dropped
        and counted in n_invalid_ids. Fetch the text of a cited article with get_article."""
        question = _clean_text(question, "question", MAX_QUESTION_CHARS)
        if not api_key_available():
            raise ToolError(
                "ANTHROPIC_API_KEY is not set, so answer_with_citations cannot run (nothing was "
                "called). Put ANTHROPIC_API_KEY=... in the repository's .env file or in the "
                "server's environment and restart the server. search_articles and get_article "
                "work without a key."
            )
        try:
            res = get_pipeline().ask(question, language)
        except ToolError:
            raise
        except ValueError as e:
            raise ToolError(str(e)) from e
        except Exception as e:
            name = type(e).__name__
            if name == "BudgetExceeded":  # the harness client refuses; surface it, never bypass it
                raise ToolError(f"Budget limit reached, no call was made: {e}") from e
            log.error("ask failed: %s", name)
            raise ToolError(f"The pipeline failed ({name}); see the server log on stderr.") from e
        return _wrap(
            status=res.status,
            answer=res.answer,
            citations=[_pointer(h) for h in res.citations],
            pointers=[_pointer(h) for h in res.pointers],
            n_invalid_ids=res.n_invalid_ids,
            parse_failed=res.parse_failed,
            ranked_articles=[{"rank": h.rank, **_pointer(h)} for h in res.hits],
            cost_usd=res.cost_usd,
            language=res.query_lang,
        )

    return server


def main() -> None:
    logging.basicConfig(
        stream=sys.stderr,
        level=os.environ.get("FEDLEX_MCP_LOG", "INFO"),
        format="%(levelname)s %(message)s",
    )
    create_server().run("stdio")


if __name__ == "__main__":
    main()
